/* ====== VẼ TIMELINE ====== */
const timeline = document.getElementById("timeline");

moc.forEach((m, i) => {
  const item = document.createElement("div");
  item.className = "item " + (i % 2 === 0 ? "left" : "right");
  item.innerHTML = `
    <div class="dot"></div>
    <div class="card" data-index="${i}">
      <div class="year">${m.nam}</div>
      <h3>${m.tieuDe}</h3>
      <p>${m.tomTat}</p>
      <span class="more">XEM THÊM &rarr;</span>
    </div>
  `;
  timeline.appendChild(item);
});

/* ====== DÒNG NĂM Ở TRANG KẾT ====== */
document.getElementById("endingYears").textContent =
  moc.map(m => m.nam).join("  —  ");

/* ====== HIỆU ỨNG FADE-IN KHI CUỘN ====== */
const observer = new IntersectionObserver(entries => {
  entries.forEach(e => {
    if (e.isIntersecting) e.target.classList.add("show");
  });
}, { threshold: 0.15 });

document.querySelectorAll(".item").forEach(el => observer.observe(el));

/* ====== POPUP ====== */
const modal = document.getElementById("modal");

document.querySelectorAll(".card").forEach(card => {
  card.addEventListener("click", () => {
    const m = moc[card.dataset.index];

    document.getElementById("modalYear").textContent = m.nam;
    document.getElementById("modalTitle").textContent = m.tieuDe;
    document.getElementById("modalDesc").textContent = m.noiDung;

    const img = document.getElementById("modalImg");
    img.src = m.anh;
    img.alt = m.tieuDe;
    img.onerror = () => { img.style.display = "none"; };
    img.style.display = "block";

    document.getElementById("modalSources").innerHTML =
      m.nguon.map(n => `<li>${n}</li>`).join("");

    modal.classList.add("open");
    document.body.style.overflow = "hidden";
  });
});

function dongModal() {
  modal.classList.remove("open");
  document.body.style.overflow = "auto";
}

document.getElementById("modalClose").addEventListener("click", dongModal);
modal.addEventListener("click", e => { if (e.target === modal) dongModal(); });
document.addEventListener("keydown", e => { if (e.key === "Escape") dongModal(); });